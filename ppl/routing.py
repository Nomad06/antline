"""Single source of truth for role-to-model routing.

routing.toml declares which provider and model backs each role: a role names
a tier, and a tier names a provider and a model. Agent
definition files under ~/.claude/agents/ are generated from it by apply();
they must never be hand-edited, because the next apply() would overwrite
the edit silently. dispatch() only tells the caller how to run a role -
for a subagent provider that means "use the Agent tool", since a Claude
Code subagent is invoked by the orchestrator, not by this process.
"""

import hashlib
import json
import re
import tomllib
from pathlib import Path

from . import forges, paths, trackers
from .errors import PplError

REQUIRED_ROLES = ("ppl-briefer", "ppl-brief-challenger", "ppl-code-worker",
                  "ppl-test-worker", "ppl-verifier", "ppl-review-responder")

# The effort values Claude Code accepts in a subagent's frontmatter.
EFFORT_LEVELS = ("low", "medium", "high", "xhigh", "max")

# The tools every harness grants a role. What depends on the project - the
# tracker's read tools, the knowledge server's tools, the forge's review tools -
# is composed on top by role_tools().
BASE_TOOLS = {
    "ppl-briefer": {
        "tools": ["Read", "Grep", "Glob"],
        "description": "Compiles a revision-bound task brief from the specification. Read-only on the repository.",
        "max_turns": 40,
    },
    "ppl-brief-challenger": {
        "tools": ["Read", "Grep", "Glob"],
        "description": "Challenges a brief against the spec text before implementation: duplicate classes, wire shapes, parked gaps. Read-only.",
        "max_turns": 40,
    },
    "ppl-code-worker": {
        "tools": ["Read", "Grep", "Glob", "Edit", "Write", "Bash"],
        "description": "Implements one task inside a fixed write boundary. Never touches tests.",
        "max_turns": 60,
    },
    "ppl-test-worker": {
        "tools": ["Read", "Grep", "Glob", "Edit", "Write", "Bash"],
        "description": "Writes tests from acceptance criteria without seeing the implementation.",
        "max_turns": 60,
    },
    "ppl-verifier": {
        "tools": ["Read", "Grep", "Glob"],
        "description": "Independently verifies a candidate against its specification. Cannot modify anything.",
        "max_turns": 40,
    },
    "ppl-review-responder": {
        "tools": ["Read", "Grep", "Glob"],
        "description": "Classifies reviewer remarks and drafts replies. Never posts and never resolves.",
        "max_turns": 30,
    },
}

_TOOL_TOKEN = re.compile(r"[A-Za-z0-9_.-]+")

# Kept as a YAML comment on the line right after the opening "---" rather than
# as text before it: frontmatter parsers anchor the opening delimiter at byte
# 0 of the file, so anything ahead of it is silently invisible to the parser
# and every declared model/tools/effort/maxTurns would be lost with it.
GENERATED_NOTICE = "# generated by ppl harness apply from routing.toml and the harness - do not edit by hand"


def agents_dir():
    # Imported here: every function below names its routing.toml document `config`.
    from . import config as config_toml
    return config_toml.agents_dir()


def load():
    path = paths.routing_file()
    try:
        with open(path, "rb") as handle:
            config = tomllib.load(handle)
    except FileNotFoundError:
        raise PplError("SCHEMA_INVALID", "no routing.toml at %s" % path)
    except tomllib.TOMLDecodeError as exc:
        raise PplError("SCHEMA_INVALID", "routing.toml at %s is not valid TOML: %s" % (path, exc))
    return _require_roles(config)


def loads(text):
    """The routing document of routing.toml's text, checked as load() checks the file."""
    try:
        config = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise PplError("SCHEMA_INVALID", "routing.toml at %s is not valid TOML: %s"
                       % (paths.routing_file(), exc))
    return _require_roles(config)


def _require_roles(config):
    missing = [r for r in REQUIRED_ROLES if r not in config.get("roles", {})]
    if missing:
        raise PplError("SCHEMA_INVALID", "routing.toml is missing roles: %s" % ", ".join(missing))
    return config


def _plain_id(value, what):
    """A model or provider id is written into an agent file's frontmatter
    unescaped, so it is one line of printable text. No stricter shape, an id
    may carry a bracketed suffix."""
    if not isinstance(value, str) or not value.strip() or not value.isprintable():
        raise PplError("SCHEMA_INVALID", "%s must be a non-empty single line of text without "
                       "control characters, got %r" % (what, value))


def tiers(config=None):
    config = config or load()
    table = config.get("tiers") or {}
    if not isinstance(table, dict):
        raise PplError("SCHEMA_INVALID", "routing.toml [tiers] must be a table")
    for name, entry in table.items():
        if (not isinstance(entry, dict) or not isinstance(entry.get("provider"), str)
                or not isinstance(entry.get("model"), str)):
            raise PplError("SCHEMA_INVALID",
                           "tier %r must be { provider = ..., model = ... } with string values"
                           % name)
        _plain_id(entry["provider"], "tier %r provider" % name)
        _plain_id(entry["model"], "tier %r model" % name)
    return table


def _concrete(config, role_name, entry):
    """A role entry with provider and model filled in from its tier. A role
    that names provider and model itself is left as written."""
    entry = dict(entry)
    tier = entry.get("tier")
    if tier is not None:
        table = tiers(config)
        if not isinstance(tier, str) or tier not in table:
            raise PplError("SCHEMA_INVALID",
                           "role %r names unknown tier %r (known: %s)"
                           % (role_name, tier, ", ".join(sorted(table)) or "none"))
        entry.setdefault("provider", table[tier]["provider"])
        entry.setdefault("model", table[tier]["model"])
    if "model" not in entry or "provider" not in entry:
        raise PplError("SCHEMA_INVALID",
                       "role %r must name a tier, or a provider and a model" % role_name)
    _plain_id(entry["provider"], "role %r provider" % role_name)
    _plain_id(entry["model"], "role %r model" % role_name)
    return entry


def _entry_and_provider(config, name):
    if name not in config.get("roles", {}):
        raise PplError("SCHEMA_INVALID", "unknown role %r" % name)
    entry = _concrete(config, name, config["roles"][name])
    provider_name = entry.get("provider")
    providers = config.get("providers", {})
    if not isinstance(provider_name, str) or provider_name not in providers:
        raise PplError("SCHEMA_INVALID",
                       "role %r references unknown provider %r" % (name, provider_name))
    return entry, providers[provider_name]


def _by_risk(config, role_name):
    """The by_risk table of a role, empty when it has none."""
    overrides = config["roles"][role_name].get("by_risk", {})
    if not isinstance(overrides, dict):
        raise PplError("SCHEMA_INVALID",
                       "role %r by_risk must be a table of risk = tier" % role_name)
    return overrides


def _by_risk_tier(config, role_name, level, tier):
    """The tier entry a by_risk override points at, refused when the tier or
    its provider is not declared."""
    table = tiers(config)
    if not isinstance(tier, str) or tier not in table:
        raise PplError("SCHEMA_INVALID",
                       "role %r by_risk.%s names unknown tier %r" % (role_name, level, tier))
    provider_name = table[tier]["provider"]
    if provider_name not in config.get("providers", {}):
        raise PplError("SCHEMA_INVALID",
                       "role %r by_risk.%s names tier %r whose provider %r is unknown"
                       % (role_name, level, tier, provider_name))
    return table[tier]


def role(name, config=None):
    config = config if config is not None else load()
    entry, provider = _entry_and_provider(config, name)
    entry["provider_config"] = provider
    return entry


def resolve(name, risk=None):
    """The role entry with the run's risk applied: `by_risk` maps a risk level
    to a tier that replaces the role's default tier for that risk only. apply()
    keeps writing the default into the agent file, the orchestrator passes the
    resolved model at dispatch [R-ROUTING-BY-RISK]."""
    config = load()
    entry = role(name)
    overrides = _by_risk(config, name)
    if risk is not None and risk in overrides:
        tier = overrides[risk]
        target = _by_risk_tier(config, name, risk, tier)
        entry["tier"] = tier
        entry["provider"] = target["provider"]
        entry["model"] = target["model"]
        entry["provider_config"] = config["providers"][target["provider"]]
        entry["risk"] = risk
    return entry


def models_in_use(risk=None):
    """Every concrete model some role resolves to. With risk=None every
    by_risk tier counts too, with a risk only that risk's overrides do."""
    config = load()
    found = set()
    for name in REQUIRED_ROLES:
        entry, _ = _entry_and_provider(config, name)
        found.add(entry["model"])
        for level, tier in _by_risk(config, name).items():
            if risk is None or level == risk:
                found.add(_by_risk_tier(config, name, level, tier)["model"])
    return found


def role_params(entry, role_name):
    """The params table of a role entry, empty when it has none."""
    params = entry.get("params")
    if params is None:
        return {}
    if not isinstance(params, dict):
        raise PplError("SCHEMA_INVALID", "role %r params must be a table" % role_name)
    return params


def _effort(entry, role_name):
    """The effort of a role entry, None when it sets none. It is written into
    an agent file's frontmatter unescaped, so only a level Claude Code accepts
    passes."""
    effort = role_params(entry, role_name).get("effort")
    if effort is not None and (not isinstance(effort, str) or effort not in EFFORT_LEVELS):
        raise PplError("SCHEMA_INVALID", "role %r effort %r is not one of %s"
                       % (role_name, effort, ", ".join(EFFORT_LEVELS)))
    return effort


def validate_config(config):
    """Refuse a routing document ppl cannot route with: a missing role, an
    unknown tier or provider, a by_risk tier that is not declared, params that
    are not a table, or an effort Claude Code does not accept."""
    missing = [r for r in REQUIRED_ROLES if r not in (config.get("roles") or {})]
    if missing:
        raise PplError("SCHEMA_INVALID", "routing.toml is missing roles: %s" % ", ".join(missing))
    tiers(config)
    for name in REQUIRED_ROLES:
        _entry_and_provider(config, name)
        for level, tier in _by_risk(config, name).items():
            _by_risk_tier(config, name, level, tier)
        _effort(config["roles"][name], name)


def preset_document(name):
    """routing.toml with every role's tier, effort and by_risk rewritten from a
    preset, nothing written. A provider and model a role pinned itself are
    replaced by its tier. The tiers, the providers and every param but effort
    stay."""
    from . import presets
    if name not in presets.PRESETS:
        raise PplError("SCHEMA_INVALID", "unknown preset %r (presets: %s)"
                       % (name, ", ".join(presets.PRESETS)))
    config = load()
    table = tiers(config)
    for role_name, spec in presets.PRESETS[name].items():
        needed = [spec["tier"]] + list(spec.get("by_risk", {}).values())
        unknown = [tier for tier in needed if tier not in table]
        if unknown:
            raise PplError("SCHEMA_INVALID", "preset %s needs tier %s, routing.toml declares: %s"
                           % (name, ", ".join(unknown), ", ".join(sorted(table))))
        entry = config["roles"].setdefault(role_name, {})
        entry.pop("provider", None)
        entry.pop("model", None)
        entry["tier"] = spec["tier"]
        entry["params"] = dict(role_params(entry, role_name), effort=spec["effort"])
        if spec.get("by_risk"):
            entry["by_risk"] = dict(spec["by_risk"])
        else:
            entry.pop("by_risk", None)
    validate_config(config)
    return config


def apply_preset(name):
    """`ppl routing preset`: the preset document written to routing.toml."""
    from . import tomlout
    config = preset_document(name)
    paths.routing_file().write_text(tomlout.dumps(config), encoding="utf-8")
    return config


def summary(config=None):
    """One row per role: its tier, the model the tier resolves to, effort and
    by_risk, for the wizard and the Agents page."""
    config = config if config is not None else load()
    rows = []
    for name in REQUIRED_ROLES:
        raw = config["roles"][name]
        entry, _ = _entry_and_provider(config, name)
        rows.append({"role": name, "description": BASE_TOOLS[name]["description"],
                     "tier": raw.get("tier"), "model": entry["model"],
                     "effort": role_params(raw, name).get("effort"),
                     "by_risk": dict(_by_risk(config, name))})
    return rows


def params_hash(entry):
    blob = json.dumps({"model": entry.get("model"), "params": entry.get("params", {})},
                      sort_keys=True)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:12]


def role_tools(name, harness_doc):
    tracker = harness_doc["tracker"]
    adapter = trackers.get(tracker["kind"])
    forge = harness_doc["forge"]
    composed = list(BASE_TOOLS[name]["tools"])
    if name == "ppl-briefer":
        composed += adapter.mcp_read_tools(tracker)
        composed += (harness_doc.get("knowledge") or {}).get("extra_tools") or []
    composed += forges.get(forge["kind"]).role_tools(name, forge)
    writes = trackers.role_write_patterns(tracker)
    tools = []
    for tool in composed:
        if any(pattern.match(tool) for pattern in writes):
            raise PplError("SCHEMA_INVALID", "role %r would hold tracker write tool %r"
                           % (name, tool))
        if not _TOOL_TOKEN.fullmatch(tool):
            raise PplError("SCHEMA_INVALID", "role %r tool %r is not a single tool name"
                           % (name, tool))
        if tool not in tools:
            tools.append(tool)
    return tools


def _overlay(name, harness_doc):
    part = Path(harness_doc["_dir"]) / "templates" / ("%s.part" % name)
    lines = []
    if name == "ppl-briefer":
        skills = (harness_doc.get("knowledge") or {}).get("skills") or []
        if skills:
            lines.append("- Load these knowledge skills before reading the tree: %s."
                         % ", ".join("`%s`" % s for s in skills))
    env = harness_doc.get("env") or {}
    if env and name in ("ppl-code-worker", "ppl-test-worker"):
        lines.append("- Environment every build command needs: %s."
                     % ", ".join("`%s=%s`" % item for item in sorted(env.items())))
    if part.is_file():
        try:
            text = part.read_text(encoding="utf-8", errors="strict").rstrip()
        except UnicodeDecodeError:
            raise PplError("SCHEMA_INVALID", "harness template %s is not UTF-8" % part)
        if text.strip():
            lines.append(text)
    if not lines:
        return ""
    return "\n\n## Project notes\n\n" + "\n".join(lines) + "\n"


def render(name, harness_doc, config=None):
    entry = role(name, config)
    meta = BASE_TOOLS[name]
    body = (paths.root() / "templates" / ("%s.md.body" % name)).read_text(encoding="utf-8")
    lines = ["---", GENERATED_NOTICE,
             "name: %s" % name,
             "description: %s" % meta["description"],
             "tools: [%s]" % ", ".join(role_tools(name, harness_doc)),
             "model: %s" % entry["model"]]
    effort = _effort(entry, name)
    if effort:
        lines.append("effort: %s" % effort)
    lines += ["maxTurns: %d" % meta["max_turns"],
              "permissionMode: default",
              "---", "", body.rstrip() + _overlay(name, harness_doc), ""]
    return "\n".join(lines)


def apply(harness_doc, target=None):
    rendered = [(name, render(name, harness_doc)) for name in REQUIRED_ROLES]
    target = Path(target) if target is not None else agents_dir()
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in rendered:
        path = target / ("%s.md" % name)
        path.write_text(text, encoding="utf-8")
        written.append(str(path))
    return written


def check_egress(name, payload, config=None):
    config = config or load()
    entry, provider = _entry_and_provider(config, name)
    if payload.get("context_files") and not provider.get("allow_source_upload", False):
        raise PplError("OWNER_DECISION",
                       "provider %s is not permitted to receive repository source. Enable "
                       "allow_source_upload explicitly or route this role elsewhere."
                       % entry["provider"])


def dispatch(name, payload):
    entry = role(name)
    check_egress(name, payload)
    kind = entry["provider_config"]["kind"]
    if kind == "subagent":
        return {"status": "use_subagent", "agent": name,
                "producer": {"provider": entry["provider"], "model": entry["model"],
                             "params_hash": params_hash(entry)}}
    # Error-vocabulary audit, cycle 2 wave E: this was EXTERNAL_BLOCKED, whose
    # documented remedy is "park, retry on the next tick" - but no adapter
    # for this provider kind is a permanent property of this ppl build, not
    # something that becomes true by waiting. The rest of this file already
    # raises SCHEMA_INVALID for a routing.toml entry that does not match
    # ppl's contract (unknown role, unknown provider, missing keys) - a
    # provider_config.kind ppl does not implement is exactly one more way
    # for routing.toml to be unsupported, not external unavailability.
    raise PplError("SCHEMA_INVALID",
                   "no adapter implemented for provider kind %r. See DESIGN section 10.2 "
                   "for the frozen contract." % kind)
